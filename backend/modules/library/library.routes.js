const express=require('express');
const service=require('./library.service');
const {requirePermission}=require('../../middleware/requirePermission');
const {asyncHandler}=require('../../middleware/asyncHandler');
const {send}=require('../../utils/respond');
const router=express.Router();
const manage=requirePermission('library.manage');
router.use(requirePermission('library.read'));
router.use((req,res,next)=>{res.set('Cache-Control','no-store');next();});
router.get('/overview',asyncHandler(async(req,res)=>send(res,await service.overview(req.user))));
router.get('/books',asyncHandler(async(req,res)=>send(res,await service.books(req.query,req.user))));
router.get('/books/:id',asyncHandler(async(req,res)=>send(res,await service.bookDetails(req.params.id,req.user))));
router.post('/books',manage,asyncHandler(async(req,res)=>send(res,await service.createBook(req.body),'Book added.',201)));
router.put('/books/:id',manage,asyncHandler(async(req,res)=>send(res,await service.updateBook(req.params.id,req.body),'Book updated.')));
router.patch('/books/:id/status',manage,asyncHandler(async(req,res)=>send(res,await service.setBookActive(req.params.id,req.body?.active),'Book status updated.')));
router.post('/books/:id/copies',manage,asyncHandler(async(req,res)=>send(res,await service.addCopies(req.params.id,req.body?.quantity),'Copies added.',201)));
router.patch('/copies/:id',manage,asyncHandler(async(req,res)=>send(res,await service.setCopyStatus(req.params.id,req.body?.status),'Copy updated.')));
router.get('/members',manage,asyncHandler(async(req,res)=>send(res,await service.members(req.query))));
router.get('/loans',manage,asyncHandler(async(req,res)=>send(res,await service.loans(req.query,req.user))));
router.get('/my-loans',requirePermission('library.self'),asyncHandler(async(req,res)=>send(res,await service.loans(req.query,req.user,true))));
router.post('/loans',manage,asyncHandler(async(req,res)=>send(res,await service.issue(req.body,req.user),'Book issued.',201)));
router.post('/loans/:id/return',manage,asyncHandler(async(req,res)=>send(res,await service.returnBook(req.params.id,req.body,req.user),'Return recorded.')));
router.post('/loans/:id/renew',manage,asyncHandler(async(req,res)=>send(res,await service.renew(req.params.id,req.body?.dueDate,req.user),'Loan renewed.')));
module.exports=router;
